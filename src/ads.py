def kw_words(k): return set(re.sub(r'[\[\]"]', "", k).lower().replace("ё", "е").split())

def check():
    errs = []
    kws = [k for g in GROUPS for k in g["kw"]]
    if not 10 <= len(kws) <= 15: errs.append(f"ключей {len(kws)}, нужно 10–15")
    for k in kws:
        if not (k.startswith('"') and k.endswith('"')) and not (k.startswith("[") and k.endswith("]")): errs.append("широкое: " + k)
    for g in GROUPS:
        heads = g["pin"] + COMMON
        if len(heads) != 15: errs.append(f"{g['name']}: заголовков {len(heads)}")
        if len(set(heads)) != len(heads): errs.append(f"{g['name']}: дубли заголовков")
        for h in heads:
            vis = re.sub(r"\{KeyWord:(.*?)\}", r"\1", h)
            if len(vis) > 30: errs.append(f"заголовок {len(vis)}>30: {h}")
            if re.search(r"!|[A-ZА-Я]{4,}|\+7|Обжито", h): errs.append("запрещённое в заголовке: " + h)
        for d in g["desc"]:
            if len(d) > 90: errs.append(f"описание {len(d)}>90: {d}")
            if "!" in d or "Обжито" in d: errs.append("запрещённое в описании: " + d)
        for p in g["path"]:
            if len(p) > 15: errs.append("path>15: " + p)
    for n in NEGATIVE:
        nw = set(n.replace("ё", "е").split())
        for k in kws:
            if nw <= kw_words(k): errs.append(f"минус «{n}» режет ключ {k}")
    return errs

def sheet(name, head, rows):
    wb = Workbook(); ws = wb.active; ws.title = "Sheet1"; ws.append(head)
    for r in rows: ws.append(r)
    for col in ws.columns: ws.column_dimensions[col[0].column_letter].width = max(12, min(48, max(len(str(c.value or "")) for c in col) + 2))
    wb.save(OUT / name)

